function ppEscape(value = "") {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function ppAsset(path = "") {
  if (/^(https?:)?\/\//.test(path) || path.startsWith("data:")) return path;
  const base = window.PP_BASE_PATH || "";
  return `${base}${path}`;
}

function ppButton(action) {
  return `<a class="btn ${ppEscape(action.style || "secondary")}" href="${ppAsset(action.href || "#")}">${ppEscape(action.label || "Open")}</a>`;
}


function applyPageMeta(layout) {
  if (!layout) return;
  if (layout.title) document.title = layout.title;
  if (layout.description) {
    let meta = document.querySelector('meta[name="description"]');
    if (!meta) {
      meta = document.createElement("meta");
      meta.name = "description";
      document.head.appendChild(meta);
    }
    meta.content = layout.description;
  }
}

function renderPPLayout() {
  const target = document.querySelector("[data-layout]");
  if (!target) return;

  const name = target.dataset.layout;
  const layout = window.PP_LAYOUTS[name];

  if (!layout) {
    target.innerHTML = `<section class="page-hero"><h1>Layout not found</h1><p class="lead">No layout named <strong>${ppEscape(name)}</strong> was found in assets/js/layouts.js.</p></section>`;
    return;
  }

  applyPageMeta(layout);
  target.innerHTML = (layout.sections || [])
    .map(section => {
      const renderer = PP_RENDERERS[section.type];
      return renderer ? renderer(section) : `<section class="card"><h2>Unknown section: ${ppEscape(section.type)}</h2></section>`;
    })
    .join("\n");
}

document.addEventListener("DOMContentLoaded", renderPPLayout);
